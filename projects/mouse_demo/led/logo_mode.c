// 单色背光灯效（经 pwm_duty_set() 下发，0 = 灭，iPWM_MAX = 满占空）
// 只保留 常亮 / 呼吸 / 关闭：常亮与关闭在 logo_process() 里直接处理，
// 这里只需呼吸一个灯效函数。
//

// 半余弦呼吸曲线：0 -> 64 两端变化慢，中间变化快。
// 与直线加减相比，转向时没有明显的速度突变，呼吸视觉更柔和。
// 表值为 64 * (1 - cos(pi * index / 64)) / 2 的四舍五入结果，
// 运行时只查表，不使用浮点运算，不增加实时路径的计算负担。
static const uint8_t breath_duty_table[iPWM_MAX+1] =
{
     0,  0,  0,  0,  1,  1,  1,  2,
     2,  3,  4,  5,  5,  6,  7,  8,
     9, 11, 12, 13, 14, 16, 17, 18,
    20, 21, 23, 24, 26, 27, 29, 30,
    32, 34, 35, 37, 38, 40, 41, 43,
    44, 46, 47, 48, 50, 51, 52, 53,
    55, 56, 57, 58, 59, 59, 60, 61,
    62, 62, 63, 63, 63, 64, 64, 64,
    64
};

/******************************************************************************
* 函数名称: effect_breatch
* 功能描述: 呼吸灯效，每调用一次沿半余弦曲线走一步
* 输入参数: 无
* 输出参数: 无
* 说    明: 速度由 led_speed_lev 控制
******************************************************************************/
void effect_breatch(void)
{
    uint8_t curve_index;

    if(led_speed_lev > delay_time_count)
    {
        delay_time_count++;
        return;
    }
    delay_time_count = 0;

    if(pwm_time_count > iPWM_MAX)            // 异常值保护，避免查表越界
        pwm_time_count = 0;

    if(!bback_led_status)                    // 变暗：从曲线末端反向查表
        curve_index = iPWM_MAX - pwm_time_count;
    else                                    // 变亮：从曲线起点正向查表
        curve_index = pwm_time_count;

    pwm_value = breath_duty_table[curve_index];
    pwm_duty_set(pwm_value);

    if(pwm_time_count >= iPWM_MAX)
    {                                       // 到达两端后换向；端点自然停留一个步进周期
        pwm_time_count = 0;
        bback_led_status = !bback_led_status;
    }
    else
    {
        pwm_time_count++;
    }
}
