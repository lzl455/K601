#define iLOW_POWER              10               // 电量 <= 10% 时电池图标闪烁

#define	POF_LVD_PIN_P33         1                // POFCON bit2~1 检测脚: 0 P23, 1 P33, 2 VBUS, 3 VDD

//----------------------------------------------
// POF 门限编码(POFCON bit8~4), 每 0x10 一档。宏按 A3 命名(0.900V 起每档 25mV),
// 同一编码在 A2 上是另一个电压(0.90V 起每档 50mV)。bat_voltage_check() 只用到这几个
//
#define	POF_THRESHOLD_1_050V	0x060
#define	POF_THRESHOLD_1_225V	0x0D0
#define	POF_THRESHOLD_1_400V	0x140
#define	POF_THRESHOLD_1_550V	0x1A0
//----------------------------------------------
//
#define	iOM6239_A3_0	        0x0A18
#define	iOM6239_A3_1	        0x0B18
//----------------------------------------------
//
//              A2版本    1M下拉 2M上拉: P33 = 电池电压/3
// VALUE = bat_voltage_check() = POF 档位+1; A2 档位 0~11 = 0.90V~1.45V, 每档 50mV(折合电池 150mV)
// (阈值宏按 A3 命名, 同一编码在 A2 上是另一个电压; 搜索范围在 A2 上覆盖电池 2.7V~4.35V)
// VALUE <= 3   电池 <3.15V         0%
// VALUE  = 4   3.15V~3.30V         5%
// VALUE  = 5   3.30V~3.45V         10%
// VALUE  = 6   3.45V~3.60V         20%
// VALUE  = 7   3.60V~3.75V         40%
// VALUE  = 8   3.75V~3.90V         60%
// VALUE  = 9   3.90V~4.05V         80%      (充电中最高到这一档, 充满信号来了才到 100%)
// VALUE >= A   >=4.05V             100%

#define	iLVD_0_VALUE            0x03
#define	iLVD_90_VALUE           0x09
#define	iLVD_100_VALUE          0x0A
//---------------------------------------------
//
//              A3版本 YFK   620k下拉 1M上拉
// VALUE < 7                    0%
// VALUE < 8                    5%
// VALUE < 9                    10%
// VALUE < A                    25%
// VALUE < B                    50%
// VALUE < C                    75%
// C< VALUE                     100%

#define	iLVD_0_VALUE_A3         (0x08-1)
#define	iLVD_90_VALUE_A3        (0x13-1)
#define	iLVD_100_VALUE_A3       (0x14-1)

